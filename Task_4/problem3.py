## problem: Division
## Task :
## Given two integers a and b:
## 1. print integer division result (a//b)
## 2. print float division result(a/b)
## input: first line integer a, second line integer b
## output : Two lines - integer division, float division
## HackerRank link: https://www.hackerrank.com/challenges/python-division/problem
## solution:
a = int(input())
b = int(input())
print(a//b)
print(a/b)
